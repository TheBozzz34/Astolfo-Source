package bypass.gui.clickgui.defaultgui;

import java.awt.Color;

public class CopiedColor {
   private final Color k;
   private final int K;
   private final int d;
   private final int G;
   private final int l;
   private final int L;

   public CopiedColor(int i, Color color, int j, int k, int l, int m) {
      this.L = i;
      this.k = color;
      this.K = j;
      this.d = k;
      this.G = l;
      this.l = m;
   }

   public int b() {
      return this.L;
   }

   public Color z() {
      return this.k;
   }

   public int X() {
      return this.G;
   }

   public int a() {
      return this.K;
   }

   public int m() {
      return this.d;
   }

   public int B() {
      return this.l;
   }
}
